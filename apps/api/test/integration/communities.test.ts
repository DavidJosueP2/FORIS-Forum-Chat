test('la bandeja es privada y marcar todas no consume avisos posteriores al corte', async t => {
  const { api, member } = await fixture(t);
  const owner = await member();
  const user = await member();
  const stranger = await member();
  const created = await api.post('/api/communities').set('Origin', origin).set('Cookie', owner.cookie).send(communityInput()).expect(201);
  const id = created.body.community.id as string;
  await api.post('/api/communities/' + id + '/membership').set('Origin', origin).set('Cookie', user.cookie).send({}).expect(201);
  await api.post('/api/posts').set('Origin', origin).set('Cookie', owner.cookie).send(postInput(id)).expect(201);
  const page = (await api.get('/api/notifications').set('Cookie', user.cookie).expect(200)).body as ForumPage<CommunityNotification>;
  assert.equal(page.items.length, 1);
  const notification = page.items[0];
  await api.post('/api/notifications/' + notification.id + '/read').set('Origin', origin).set('Cookie', stranger.cookie).send({}).expect(404);
  await api.post('/api/posts').set('Origin', origin).set('Cookie', owner.cookie).send(postInput(id, 'Posterior')).expect(201);
  await api.post('/api/notifications/read-all').set('Origin', origin).set('Cookie', user.cookie).send({ throughId: notification.id }).expect(201);
  assert.equal((await api.get('/api/notifications/count').set('Cookie', user.cookie)).body.unreadCount, 1);
  const recent = (await api.get('/api/notifications?limit=1').set('Cookie', user.cookie)).body as ForumPage<CommunityNotification>;
  assert.equal(recent.hasMore, true);
  const older = (await api.get('/api/notifications?before=' + recent.nextCursor).set('Cookie', user.cookie)).body as ForumPage<CommunityNotification>;
  assert.equal(older.items[0].id, notification.id);
  assert.ok(older.items[0].readAt);
  await api.post('/api/notifications/' + recent.items[0].id + '/read').set('Origin', origin).set('Cookie', user.cookie).send({}).expect(201);
  assert.equal((await api.get('/api/notifications/count').set('Cookie', user.cookie)).body.unreadCount, 0);
});
