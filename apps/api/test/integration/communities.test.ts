import { test } from 'node:test';
import type { TestContext } from 'node:test';
import assert from 'node:assert/strict';
import { randomUUID } from 'node:crypto';
import request from 'supertest';
import type { Community, CommunityNotification, ForumPage } from '@messages/contracts';
import { randomToken, tokenHash } from '../../src/modules/auth/auth-crypto.js';
import { createTestApplication } from '../support/application.js';

const origin = 'http://127.0.0.1:5173';
const communityInput = (name = 'Lecturas compartidas') => ({ name, description: 'Un lugar para compartir ideas.', requestId: randomUUID() });
const postInput = (communityId: string, title = 'Una idea nueva') => ({ title, body: 'Texto para conversar.', topicId: 'general', communityId, requestId: randomUUID() });
async function fixture(t: TestContext) {
  const instance = await createTestApplication({ auth: true });
  t.after(() => instance.app.close());
  await instance.app.init();
  const member = async () => {
    const id = randomUUID();
    const token = randomToken();
    await instance.database.query('INSERT INTO users(id,email,display_name,email_verified_at) VALUES($1,$2,$3,$4)', [id, id + '@example.test', 'Miembro', new Date()]);
    await instance.database.query('INSERT INTO auth_sessions(id,user_id,token_hash,expires_at) VALUES($1,$2,$3,$4)', [randomUUID(), id, tokenHash(token), new Date(Date.now() + 3600000)]);
    return { id, cookie: 'foris_session=' + token };
  };
  return { ...instance, api: request(instance.server), member };
}
test('comunidades públicas, acciones privadas y creación idempotente con fundador como miembro', async t => {
  const { api, member } = await fixture(t);
  assert.equal((await api.get('/api/communities').expect(200)).body.items.length, 0);
  await api.post('/api/communities').set('Origin', origin).send(communityInput()).expect(401);
  await api.get('/api/communities?scope=mine').expect(401);
  await api.get('/api/notifications').expect(401);
  const owner = await member();
  const input = communityInput();
  const created = await api.post('/api/communities').set('Origin', origin).set('Cookie', owner.cookie).send(input).expect(201);
  const item = created.body.community as Community;
  assert.equal(item.memberCount, 1);
  assert.equal(item.isFavorite, true);
  assert.deepEqual(item.membership, { role: 'owner', notifyPosts: true });
  const retry = await api.post('/api/communities').set('Origin', origin).set('Cookie', owner.cookie).send(input).expect(200);
  assert.equal(retry.body.community.id, item.id);
  await api.post('/api/communities').set('Origin', origin).set('Cookie', owner.cookie).send({ ...input, description: 'Otro propósito' }).expect(409);
  await api.post('/api/communities').set('Origin', origin).set('Cookie', owner.cookie).send(communityInput('LECTURAS COMPARTIDAS')).expect(409);
  const publicItem = (await api.get('/api/communities/' + item.id).expect(200)).body as Community;
  assert.equal(publicItem.membership, null);
  assert.equal(publicItem.isFavorite, false);
  await api.delete('/api/communities/' + item.id + '/membership').set('Origin', origin).set('Cookie', owner.cookie).send({}).expect(409);
});
test('favoritas independientes, membresías sin duplicar y preferencias aisladas por cuenta', async t => {
  const { api, member } = await fixture(t);
  const owner = await member();
  const user = await member();
  const created = await api.post('/api/communities').set('Origin', origin).set('Cookie', owner.cookie).send(communityInput()).expect(201);
  const id = created.body.community.id as string;
  const path = '/api/communities/' + id;
  const favorite = await api.patch(path + '/preferences').set('Origin', origin).set('Cookie', user.cookie).send({ favorite: true }).expect(200);
  assert.equal(favorite.body.isFavorite, true);
  assert.equal(favorite.body.membership, null);
  await api.patch(path + '/preferences').set('Origin', origin).set('Cookie', user.cookie).send({ notifyPosts: true }).expect(403);
  await api.post(path + '/membership').set('Origin', origin).set('Cookie', user.cookie).send({}).expect(201);
  const again = await api.post(path + '/membership').set('Origin', origin).set('Cookie', user.cookie).send({}).expect(201);
  assert.equal(again.body.memberCount, 2);
  assert.equal(again.body.membership.notifyPosts, true);
  await api.patch(path + '/preferences').set('Origin', origin).set('Cookie', user.cookie).send({ notifyPosts: false }).expect(200);
  assert.equal((await api.get(path).set('Cookie', owner.cookie)).body.membership.notifyPosts, true);
  const favorites = (await api.get('/api/communities?scope=favorites').set('Cookie', user.cookie)).body as ForumPage<Community>;
  assert.deepEqual(favorites.items.map(item => item.id), [id]);
  const left = await api.delete(path + '/membership').set('Origin', origin).set('Cookie', user.cookie).send({}).expect(200);
  assert.equal(left.body.left, true);
  const afterLeaving = await api.get(path).set('Cookie', user.cookie).expect(200);
  assert.equal(afterLeaving.body.memberCount, 1);
  assert.equal(afterLeaving.body.membership, null);
  assert.equal(afterLeaving.body.isFavorite, true);
  assert.equal((await api.get('/api/communities?scope=mine').set('Cookie', user.cookie)).body.items.length, 0);
  await api.delete(path + '/membership').set('Origin', origin).set('Cookie', user.cookie).send({}).expect(200);
  assert.equal((await api.get(path)).body.memberCount, 1);
});
